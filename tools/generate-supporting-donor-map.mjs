import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { teams } from '../src/content/teams.js';
import { assignSupportingDonors, supportingDonorIds } from '../src/content/supporting-donor-assignment.js';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const output = path.join(root, 'src/content/supporting-donor-map.js');
const seed = 'jamverse96-support-donors-issue7-v1';
const assignments = assignSupportingDonors(teams, { seed });
const donorCounts = Object.fromEntries(supportingDonorIds.map(id => [id, 0]));
for (const [playerId, donorId] of Object.entries(assignments)) if (playerId !== donorId) donorCounts[donorId]++;
const generated = `// Generated by tools/generate-supporting-donor-map.mjs; edit the seed/constraints, then regenerate.\nexport const supportingDonorSeed = ${JSON.stringify(seed)};\nexport const supportingDonorMap = Object.freeze(${JSON.stringify(assignments, null, 2)});\nexport const supportingDonorCounts = Object.freeze(${JSON.stringify(donorCounts, null, 2)});\n`;
await writeFile(output, generated);
console.log(`Wrote ${Object.keys(assignments).length} stable donor assignments to ${path.relative(root, output)}`);
console.log(donorCounts);
