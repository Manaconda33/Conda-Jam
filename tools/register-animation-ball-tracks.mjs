import { randomUUID } from 'node:crypto';
import { open, mkdir, rename, unlink } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { canonicalJson } from './captain-studio/canonical-json.mjs';

function isRecord(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value) && Object.getPrototypeOf(value) === Object.prototype;
}

function validateRegistry(data) {
  if (!isRecord(data) || !isRecord(data.athleteBallTracks) || !isRecord(data.athleteBallTrackProvenance)) {
    throw new TypeError('Track and provenance registries are required');
  }
  canonicalJson(data.athleteBallTracks);
  canonicalJson(data.athleteBallTrackProvenance);
}

export function renderBallTrackRegistry(data) {
  validateRegistry(data);
  return [
    `// Generated by tools/register-animation-ball-tracks.mjs; do not edit by hand.`,
    `export const athleteBallTracks = ${canonicalJson(data.athleteBallTracks)};`,
    `export const athleteBallTrackProvenance = ${canonicalJson(data.athleteBallTrackProvenance)};`,
    '',
  ].join('\n');
}

export async function writeBallTrackRegistry(data, outputPath) {
  if (typeof outputPath !== 'string' || !outputPath) throw new TypeError('Output path is required');
  const target = resolve(outputPath), directory = dirname(target);
  await mkdir(directory, { recursive: true });
  const temporary = `${target}.${process.pid}.${randomUUID()}.tmp`;
  let handle;
  try {
    handle = await open(temporary, 'wx', 0o644);
    await handle.writeFile(renderBallTrackRegistry(data), 'utf8');
    await handle.sync();
    await handle.close();
    handle = undefined;
    await rename(temporary, target);
  } finally {
    await handle?.close();
    await unlink(temporary).catch(error => { if (error.code !== 'ENOENT') throw error; });
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const data = await import('../src/content/animation-ball-tracks.js');
  await writeBallTrackRegistry({
    athleteBallTracks: data.athleteBallTracks,
    athleteBallTrackProvenance: data.athleteBallTrackProvenance,
  }, resolve('src/content/animation-ball-tracks.js'));
}
