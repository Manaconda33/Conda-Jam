import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { animationMirrorPolicy } from '../../src/content/animation-mirror-policy.js';
import { decodeImage, inspectFrames } from '../animation-assets.mjs';

const root = new URL('../../', import.meta.url);
const readJson = async path => JSON.parse(await readFile(new URL(path, root), 'utf8'));
const writeJson = async (path, value) => writeFile(new URL(path, root), `${JSON.stringify(value, null, 2)}\n`);

const registrationPath = 'tools/generate-art/echo-catwalk-23-clip-registration-layouts.json';
const trackPath = 'tools/generate-art/echo-catwalk-runtime-ball-tracks.json';
const registration = await readJson(registrationPath);
const trackRecord = await readJson(trackPath);
const tracks = trackRecord.tracks;
if (registration.length !== 23 || Object.keys(tracks).length !== 23) {
  throw new Error('Echo package needs 23 new clips and 23 athlete-specific ball tracks');
}
if (registration.some(entry => !entry.provenance?.repack?.minimumMarginsPx ||
    Object.values(entry.provenance.repack.minimumMarginsPx).some(px => px < 5))) {
  throw new Error('Echo package must pass five-pixel margins before registration');
}

const applyTrack = entry => {
  const track = tracks[entry.clip];
  if (!track) return;
  entry.provenance ??= {};
  entry.provenance.runtimeBallTrack = structuredClone(track);
  entry.provenance.separateBall = true;
};
for (const entry of registration) applyTrack(entry);
await writeJson(registrationPath, registration);

const layoutPaths = [
  'tools/generate-art/echo-catwalk-locomotion-layouts.json',
  'tools/generate-art/echo-catwalk-shoot10-layouts.json',
];
for (const path of layoutPaths) {
  const value = await readJson(path);
  const entries = Array.isArray(value) ? value : [value];
  for (const entry of entries) if (entry.athlete === 'echo-catwalk') applyTrack(entry);
  await writeJson(path, value);
}

const manifestPath = 'public/assets/animation/manifest.json';
const manifest = await readJson(manifestPath);
const character = manifest.characters['echo-catwalk'];
if (!character) throw new Error('Echo baseline character manifest is missing');
Object.assign(character, animationMirrorPolicy['echo-catwalk']);
for (const entry of registration) {
  const asset = { ...entry, reviewed: true };
  asset.source = 'imagegen';
  const atlas = await decodeImage(fileURLToPath(new URL(asset.src.slice(2), root)));
  const decodedFrames = inspectFrames(atlas, asset.frames);
  if (decodedFrames.some(frame => frame.error || !frame.visiblePixels) ||
      new Set(decodedFrames.map(frame => frame.hash)).size !== decodedFrames.length) {
    throw new Error(`${entry.clip} packed frames must be nonblank and unique`);
  }
  asset.frames = decodedFrames.map(({ index, visiblePixels, ...frame }) => frame);
  asset.sha256 = atlas.sha256;
  asset.provenance ??= {};
  asset.provenance.status = 'accepted after native contact review at 100% and 120%';
  asset.provenance.integrationReview = {
    status: 'passed',
    previewDirectory: 'tools/generate-art/previews/echo-catwalk-package-20261024/',
    zooms: [100, 120],
    summaryCapturesPerZoom: 87,
    actionFrameCapturesPerZoom: 572,
    review: 'Both facings; pose identity and production selection, separate ball contacts, and carried/free-ball ownership.'
  };
  character.directions.right[entry.clip] = asset;
}
for (const [key, asset] of Object.entries(character.directions.right)) {
  const track = tracks[key];
  if (track) {
    asset.provenance ??= {};
    asset.provenance.runtimeBallTrack = structuredClone(track);
    asset.provenance.separateBall = true;
  }
}
await writeJson(manifestPath, manifest);
await writeFile(new URL('src/content/animation-assets.js', root),
  `// Generated by tools/register-animation-atlas.mjs from the production manifest.\n`+
  `export const animationAssetManifest = ${JSON.stringify(manifest, null, 2)};\n`);

const animationPath = new URL('src/core/animation.js', root);
let animation = await readFile(animationPath, 'utf8');
const marker = "},'sol-meridian':{";
const existingStart = animation.indexOf(",'echo-catwalk':");
if (existingStart >= 0) {
  const existingEnd = animation.indexOf(marker, existingStart);
  if (existingEnd < 0) throw new Error('Could not find end of existing Echo ball-track record');
  animation = animation.slice(0, existingStart) + `,'echo-catwalk':${JSON.stringify(tracks)}` + animation.slice(existingEnd + 1);
} else {
  if (!animation.includes(marker)) throw new Error('Could not find athlete ball-track insertion point');
  animation = animation.replace(marker, `},'echo-catwalk':${JSON.stringify(tracks)},'sol-meridian':{`);
}
await writeFile(animationPath, animation);

trackRecord.status = 'accepted after native visual contact review';
trackRecord.basis = 'Echo-specific frame-indexed values stored separately from sprite art. Authored source tracks are taken from Echo layout provenance where available; remaining points were calibrated against hand contacts and court contact in actual native Canvas captures at 100% and 120%.';
await writeJson(trackPath, trackRecord);
console.log('Registered the reviewed Echo Catwalk package with 23 separate ball tracks.');
