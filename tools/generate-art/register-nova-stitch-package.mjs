import { readFile, writeFile } from 'node:fs/promises';
import { animationMirrorPolicy } from '../../src/content/animation-mirror-policy.js';

const readJson = async path => JSON.parse(await readFile(path, 'utf8'));
const writeJson = async (path, value) => writeFile(path, `${JSON.stringify(value, null, 2)}\n`);
const root = new URL('../../', import.meta.url);
const relative = path => new URL(path, root);
const trackRecord = await readJson(relative('tools/generate-art/nova-stitch-runtime-ball-tracks.json'));
const tracks = trackRecord.tracks;
const registrationPath = relative('tools/generate-art/nova-stitch-23-clip-registration-layouts.json');
const registration = await readJson(registrationPath);
if (registration.length !== 23 || Object.keys(tracks).length !== 23) throw new Error('Nova action registration requires exactly 23 ball-bearing clips');

const acceptedReview = {
  status: 'accepted',
  notes: 'Nova Stitch source and repacked atlas reviewed for identity, full human anatomy, pose separation, alpha, and five-pixel edge clearance. Native Canvas captures at 100% and 120% select production art across all poses in both facings; the separate Nova-specific ball tracks were visually calibrated against hand contacts, including catch, release, and final carried ticks.'
};
const applyTrack = (entry, review = false) => {
  const track = tracks[entry.clip];
  if (!track) return;
  entry.provenance ??= {};
  entry.provenance.runtimeBallTrack = structuredClone(track);
  entry.provenance.separateBall = true;
  if (review) {
    entry.provenance.review ??= {};
    entry.provenance.review.status = 'accepted';
    entry.provenance.review.integrationReview = structuredClone(acceptedReview);
  }
};

for (const entry of registration) applyTrack(entry, true);
await writeJson(registrationPath, registration);

for (const path of ['tools/generate-art/nova-stitch-locomotion-layouts.json', 'tools/generate-art/nova-stitch-shoot10-layouts.json']) {
  const layoutPath = relative(path);
  const value = await readJson(layoutPath);
  const entries = Array.isArray(value) ? value : [value];
  for (const entry of entries) if (entry.athlete === 'nova-stitch') applyTrack(entry, true);
  await writeJson(layoutPath, value);
}

const manifestPath = relative('public/assets/animation/manifest.json');
const manifest = await readJson(manifestPath);
const character = manifest.characters['nova-stitch'];
Object.assign(character, animationMirrorPolicy['nova-stitch']);
for (const [key, asset] of Object.entries(character.directions.right)) {
  asset.reviewed = true;
  const track = tracks[key];
  if (track) {
    asset.provenance ??= {};
    asset.provenance.runtimeBallTrack = structuredClone(track);
    asset.provenance.separateBall = true;
    asset.provenance.status = 'accepted source; Nova-specific separate-ball track passed native 100%/120% contact review';
  }
  if (asset.provenance?.repack?.script === 'tools/generate-art/repack-nova-stitch-package.py') {
    asset.provenance.review ??= {};
    asset.provenance.review.status = 'accepted';
    asset.provenance.review.integrationReview = structuredClone(acceptedReview);
  }
}
if (Object.keys(character.directions.right).length !== 29) throw new Error('Nova must finish with 29 reviewed clips');
await writeJson(manifestPath, manifest);
await writeFile(relative('src/content/animation-assets.js'), `// Generated by tools/register-animation-atlas.mjs from the production manifest.\nexport const animationAssetManifest = ${JSON.stringify(manifest, null, 2)};\n`);

trackRecord.status = 'accepted';
trackRecord.basis = 'Nova-specific frame-indexed tracks calibrated against Nova’s own authored hand positions and reviewed in native Canvas captures at 100% and 120% zoom. The four contact corrections and their review points are retained in calibrationNotes and the preview reports.';
await writeJson(relative('tools/generate-art/nova-stitch-runtime-ball-tracks.json'), trackRecord);
console.log('Finalized Nova Stitch: 29 reviewed clips, 23 athlete-specific ball tracks.');
